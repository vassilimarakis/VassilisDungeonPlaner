Locale.translations = { enUS = enUS, deDE = deDE }
local valid = { auto = true, deDE = true, enUS = true }

function Locale.Preference()
    local preference = GuildBoardDB and GuildBoardDB.language
    return valid[preference] and preference or "auto"
end
function Locale.Current()
    local preference = Locale.Preference()
    if preference ~= "auto" then return preference end
    return GetLocale() == "deDE" and "deDE" or "enUS"
end
function GB.L(key, ...)
    local value = Locale.translations[Locale.Current()][key] or enUS[key] or key
    if select("#", ...) > 0 then return string.format(value, ...) end
    return value
end
function Locale.PreferenceName()
    local preference = Locale.Preference()
    return preference == "auto" and GB.L("LANGUAGE_AUTO") or (preference == "deDE" and "Deutsch" or "English")
end
function Locale.SetPreference(preference)
    if not valid[preference] or not GuildBoardDB then return false end
    GuildBoardDB.language = preference
    if GB.UI and GB.UI.Relocalize then GB.UI.Relocalize() end
    return true
end
-- Resolve names at use time, including after a language change.
function Locale.Names(keys)
    return setmetatable({}, { __index = function(_, key) return GB.L(keys[key]) end })
end
